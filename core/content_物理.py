        "模型三（三场共存，匀速直线运动）：重力、电场力、洛伦兹力三力平衡，mg=qE 且 qvB 与前两力的合力等大反向。解题时先将重力和电场力合成为一个「等效重力」，问题转化为粒子在等效重力场和磁场中的运动。若粒子做匀速圆周运动，则重力与电场力必须平衡（mg=qE），洛伦兹力单独提供向心力。",
        "模型四（三场共存，复杂曲线运动）：当重力和电场力不平衡时，粒子做复杂曲线运动。处理方法：①将运动分解为沿合力方向和垂直合力方向；②利用动能定理（洛伦兹力不做功，只有重力和电场力做功）求速度大小；③利用几何关系（圆周运动的圆心、半径、圆心角）求位移和时间；④多段运动时，每一段分别分析，注意衔接点的速度方向和大小。",
